"""Write ui_icons.c: antialiased icons as LVGL 8-bit alpha images.

LVGL 6 draws thick diagonal lines with stepped edges and blobby joints, and
its symbol font has no diagonal chevrons or "Wi-Fi off", so these are drawn
here instead, smoothed like font glyphs. Alpha images take their color from
the style (image.color), like text.

    python tools/gen_icons.py ui_icons.c
"""
import math
import sys

SS = 6  # supersampling per axis


def dist_seg(px, py, ax, ay, bx, by):
    dx, dy = bx - ax, by - ay
    t = max(0.0, min(1.0, ((px - ax) * dx + (py - ay) * dy) / (dx * dx + dy * dy)))
    cx, cy = ax + t * dx, ay + t * dy
    return math.hypot(px - cx, py - cy)


def render(w, h, segments, width):
    """Round capped strokes along segments ((x0, y0), (x1, y1)), in pixel centers."""
    img = [[0] * w for _ in range(h)]
    for y in range(h):
        for x in range(w):
            hits = 0
            for sy in range(SS):
                for sx in range(SS):
                    px = x + (sx + 0.5) / SS - 0.5
                    py = y + (sy + 0.5) / SS - 0.5
                    d = min(dist_seg(px, py, a[0], a[1], b[0], b[1]) for a, b in segments)
                    if d <= width / 2:
                        hits += 1
            img[y][x] = round(255 * hits / (SS * SS))
    return img


def flip(img, fx, fy):
    h, w = len(img), len(img[0])
    return [[img[h - 1 - y if fy else y][w - 1 - x if fx else x] for x in range(w)] for y in range(h)]


def c_image(name, img):
    out = ['static const uint8_t %s_map[] = {' % name]
    for row in img:
        out.append('    ' + ', '.join('0x%02x' % v for v in row) + ',')
    out += ['};', '',
            'const lv_img_dsc_t %s = {' % name,
            '    .header = { .cf = LV_IMG_CF_ALPHA_8BIT, .always_zero = 0, .w = %d, .h = %d },' % (len(img[0]), len(img)),
            '    .data_size = sizeof(%s_map),' % name,
            '    .data = %s_map' % name,
            '};']
    return '\n'.join(out)


# Diagonal jog chevrons, 18x18: the up chevron turned 45 degrees, a corner
# with one arm along each axis, the stroke of a 16 px glyph
chevron = render(18, 18, [((13, 4.5), (3.5, 4.5)), ((13, 4.5), (13, 14))], 3.0)

# Wi-Fi off: a slash over the Wi-Fi glyph, 22x20. The wide one is drawn in
# the status bar color first, to cut a gap around the thin one.
slash = [((2.5, 1.5), (19.5, 18.5))]
slash_gap = render(22, 20, slash, 5.5)
slash_line = render(22, 20, slash, 2.2)

# Host (a PC talking to the machine): a monitor on a stand, 22x18
host = render(22, 18, [((2.5, 1.5), (18.5, 1.5)), ((18.5, 1.5), (18.5, 11.5)), ((18.5, 11.5), (2.5, 11.5)),
                       ((2.5, 11.5), (2.5, 1.5)), ((10.5, 12.5), (10.5, 15)), ((6, 15.5), (15, 15.5))], 2.0)

images = [
    ('ui_arrow_up_right', chevron),
    ('ui_arrow_up_left', flip(chevron, True, False)),
    ('ui_arrow_down_right', flip(chevron, False, True)),
    ('ui_arrow_down_left', flip(chevron, True, True)),
    ('ui_slash_gap', slash_gap),
    ('ui_slash', slash_line),
    ('ui_host', host),
]

header = '''/*
 * ui_icons.c - Icons as 8-bit alpha images
 *
 * Part of grblHAL TFT Plugin
 *
 * Generated by tools/gen_icons.py, do not edit. Diagonal jog chevrons and
 * the slash over the Wi-Fi symbol when it is down: LVGL 6 has no such
 * glyphs and draws thick diagonal lines with jagged edges. Colored like
 * text by the style (image.color).
 */

#include "tft_config.h"

#if TFT_ENABLE

#include <lvgl.h>

#include "ui_icons.h"
'''

body = '\n\n'.join(c_image(n, i) for n, i in images)
open(sys.argv[1], 'w', newline='\n').write(header + '\n' + body + '\n\n#endif // TFT_ENABLE\n')
